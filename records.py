"""Check a records folder and write its INDEX.md and graph.json. Standard library only.

    py records.py <records-folder>

A records folder holds one Markdown file per idea in ideas/, each with front matter (see templates/TEMPLATE.md).
Links between ideas (helps, related, blocked_by) must point at files that exist. Repo links are gh:owner/name or a full URL.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

STATUSES = ["idea", "exploring", "prototype", "in-use", "parked", "dropped"]
LIST_FIELDS = ["tags", "problems", "repos", "data", "helps", "related", "blocked_by"]
REQUIRED = ["id", "title", "status", "updated"]


def parse(path: Path) -> dict:
    """Read the front matter. shortcut: only `key: value` and `key: [a, b]` lines, swap in PyYAML if entries need more."""
    m = re.match(r"---\n(.*?)\n---\n(.*)", path.read_text(encoding="utf-8").replace("\r\n", "\n"), re.S)
    if not m:
        raise ValueError(f"{path.name}: no front matter")
    meta = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        value = value.split(" #")[0].strip()
        meta[key.strip()] = [v.strip() for v in value[1:-1].split(",") if v.strip()] if value.startswith("[") else value
    for f in LIST_FIELDS:
        meta.setdefault(f, [])
    meta["body"] = m.group(2)
    return meta


def link(ref: str) -> str:
    if ref.startswith(("http://", "https://")):
        return ref
    return f"https://github.com/{ref[3:]}" if ref.startswith("gh:") else ""


def check(ideas: dict) -> list[str]:
    problems = []
    for i, m in ideas.items():
        problems += [f"{i}: missing {f}" for f in REQUIRED if not m.get(f)]
        if m.get("id") != i:
            problems.append(f"{i}: id '{m.get('id')}' does not match the file name")
        if m.get("status") not in STATUSES:
            problems.append(f"{i}: status '{m.get('status')}' is not one of {STATUSES}")
        for f in ("helps", "related", "blocked_by"):
            problems += [f"{i}: {f} -> '{t}' has no file in ideas/" for t in m[f] if t not in ideas]
        problems += [f"{i}: repo '{r}' must be gh:owner/name or a full URL" for r in m["repos"] if not link(r)]
    return problems


def graph(ideas: dict) -> dict:
    nodes = {i: {"id": i, "type": "idea", "title": m["title"], "status": m["status"]} for i, m in ideas.items()}
    edges = []
    for i, m in ideas.items():
        for f, kind in (("problems", "problem"), ("repos", "repo"), ("data", "data")):
            for t in m[f]:
                nodes.setdefault(t, {"id": t, "type": kind})
                edges.append({"from": i, "to": t, "type": f})
        edges += [{"from": i, "to": t, "type": f} for f in ("helps", "related", "blocked_by") for t in m[f]]
    return {"nodes": list(nodes.values()), "edges": edges}


def index(ideas: dict, problems: list[str]) -> str:
    out = ["# Idea index", "", "Generated by `records.py`. Do not edit by hand.", ""]
    for s in STATUSES:
        rows = sorted((m for m in ideas.values() if m["status"] == s), key=lambda m: m["id"])
        if rows:
            out += [f"## {s} ({len(rows)})", "", "| Idea | Updated | Problems |", "|---|---|---|"]
            out += [f"| [{m['title']}](ideas/{m['id']}.md) | {m['updated']} | {', '.join(m['problems'])} |" for m in rows]
            out.append("")
    shared = {}
    for m in ideas.values():
        for p in m["problems"]:
            shared.setdefault(p, []).append(m["id"])
    out += ["## Problems and the ideas that touch them", ""]
    out += [f"- **{p}**: {', '.join(sorted(ids))}" for p, ids in sorted(shared.items(), key=lambda kv: -len(kv[1]))]
    out += ["", "## Links between ideas", "", "```mermaid", "graph LR"]
    out += [f"  {i} -->|{f}| {t}" for i, m in sorted(ideas.items()) for f in ("helps", "related", "blocked_by") for t in m[f]]
    out += ["```", ""]
    if problems:
        out += ["## Checks that failed", ""] + [f"- {p}" for p in problems] + [""]
    return "\n".join(out)


def build(root: Path) -> int:
    ideas = {p.stem: parse(p) for p in sorted((root / "ideas").glob("*.md"))}
    problems = check(ideas)
    (root / "INDEX.md").write_text(index(ideas, problems), encoding="utf-8")
    g = graph(ideas)
    (root / "graph.json").write_text(json.dumps(g, indent=1), encoding="utf-8")
    print(f"{len(ideas)} ideas, {len(g['nodes'])} nodes, {len(g['edges'])} edges")
    for p in problems:
        print("CHECK:", p)
    return 1 if problems else 0


def _selftest() -> None:
    ideas = {"a": {"id": "a", "title": "A", "status": "idea", "updated": "2026-01-01", "repos": ["gh:x/y", "bad"],
                   "helps": ["b"], **{f: [] for f in ("tags", "problems", "data", "related", "blocked_by")}}}
    found = check(ideas)
    assert any("'b' has no file" in p for p in found), found
    assert any("'bad' must be" in p for p in found), found
    assert link("gh:o/r") == "https://github.com/o/r" and link("https://x.org/y") == "https://x.org/y"


if __name__ == "__main__":
    _selftest()
    sys.exit(build(Path(sys.argv[1]) if sys.argv[1:] else Path(".")))
